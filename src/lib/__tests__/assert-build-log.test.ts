/**
 * Build-log guard (scripts/ci/assert-build-log.mjs): fails the CI run when `next build` reports an unresolved module or import.
 *
 * Background: a package that was imported but never declared (`nodemailer`) produced `Module not found: Can't resolve 'nodemailer'`
 * as a build WARNING; the build exited 0 and printed "Compiled successfully", so it shipped green. These tests prove the guard
 *   (1) fails on REAL logs that contain each diagnostic class (two from actual CI runs, two generated with the pinned Next version),
 *   (2) passes the REAL clean CI log, including the legitimate warnings it contains,
 *   (3) is not fooled by text that merely mentions the words (code frames, application logs, other warnings),
 *   (4) fails closed on an empty or incomplete log, and
 *   (5) really fails a CI gate: the same command that the workflow runs, through scripts/ci/gate.sh, returns non-zero and is recorded.
 * Fixtures: scripts/ci/fixtures/build-logs (README there explains each file).
 */
import { describe, it, expect } from "vitest";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { pathToFileURL } from "node:url";

const root = path.resolve(__dirname, "../../..");
const FX = path.join(root, "scripts/ci/fixtures/build-logs");
const fixture = (name: string) => fs.readFileSync(path.join(FX, name), "utf8");
const GUARD = path.join(root, "scripts/ci/assert-build-log.mjs");
type Finding = { line: number; kind: string; from: string | null; text: string };
type Analysis = { findings: Finding[]; sawCompileMarker: boolean; ignoredWarnings: number; problems: string[]; lineCount: number };
// eslint-disable-next-line @typescript-eslint/no-explicit-any
const mod: Promise<any> = import(/* @vite-ignore */ pathToFileURL(GUARD).href);
const analyze = async (t: string): Promise<Analysis> => (await mod).analyze(t);
const verdict = async (t: string) => { const a = await analyze(t); return a.findings.length === 0 && a.problems.length === 0; };

/** Inserts text into the real clean log right after the compile marker, where webpack prints its diagnostics. */
const inject = (block: string) => fixture("clean-real-ci.txt").replace(/(Compiled successfully in [^\n]*\n)/, `$1${block}\n`);

describe("REAL logs that must FAIL", () => {
  it("the log of the build that shipped the defect (CI run 41228134426): nodemailer, with the importing file", async () => {
    const a = await analyze(fixture("nodemailer-warning-real-ci.txt"));
    expect(a.sawCompileMarker).toBe(true); // the build itself reported success: this is exactly what went unnoticed
    expect(a.findings).toHaveLength(1);
    expect(a.findings[0]).toMatchObject({ kind: "module-not-found", from: "./src/lib/email.ts" });
    expect(a.findings[0]!.text).toContain("Can't resolve 'nodemailer'");
  });
  it("unresolvable dynamic import and a named import the module does not export (generated by Next 15.5.28)", async () => {
    const a = await analyze(fixture("unresolved-dynamic-and-missing-export-real.txt"));
    expect(a.sawCompileMarker).toBe(true);
    expect(a.findings.map((f) => f.kind).sort()).toEqual(["missing-export", "missing-export", "module-not-found"]); // reported once per compiler
    expect(a.findings.every((f) => f.from === "./src/app/api/zz-probe/route.ts")).toBe(true);
  });
  it("unresolvable static import: a hard error (the build fails too, the guard reaches the same verdict, without an extra 'incomplete log' complaint)", async () => {
    const a = await analyze(fixture("unresolved-static-error-real.txt"));
    expect(a.findings).toHaveLength(1);
    expect(a.findings[0]).toMatchObject({ kind: "module-not-found", from: "./src/app/api/zz-probe/route.ts" });
    expect(a.problems).toEqual([]);
  });
});

describe("REAL clean log must PASS (and keeps its legitimate warnings)", () => {
  it("CI run 41449971382: no findings; the warnings it does contain are counted and ignored, not failed", async () => {
    const a = await analyze(fixture("clean-real-ci.txt"));
    expect(a).toMatchObject({ findings: [], problems: [], sawCompileMarker: true });
    expect(fixture("clean-real-ci.txt")).toContain("⚠ No build cache found"); // proof the fixture really holds a normal warning
    expect(fixture("clean-real-ci.txt")).toContain("[env] WARNING:");
    expect(a.ignoredWarnings).toBeGreaterThan(5);
  });
});

describe("no false positives: text that only mentions the words, and ordinary warnings", () => {
  const BENIGN: [string, string][] = [
    ["webpack 'Critical dependency' warning (a different, normal warning)", "./node_modules/some-lib/index.js\nCritical dependency: the request of a dependency is an expression\n\nImport trace for requested module:\n./node_modules/some-lib/index.js"],
    ["Next missing-build-cache warning", " ⚠ No build cache found. Please configure build caching for faster rebuilds."],
    ["application [env] warnings", "[env] WARNING: SENTRY_DSN not set in production. Errors will only be logged locally."],
    ["Node deprecation warning", "(node:1234) [DEP0040] DeprecationWarning: The `punycode` module is deprecated."],
    ["source code frame quoting the words (plain)", "  12 | throw new Error(\"Module not found: Can't resolve 'x'\");"],
    ["source code frame quoting the words (marked line)", "> 12 | const msg = \"Module not found: Can't resolve 'x'\";"],
    ["source code frame quoting the words (ANSI-coloured, as Next prints it)", "\u001b[31m\u001b[1m>\u001b[22m\u001b[39m\u001b[90m 11 |\u001b[39m \u001b[32m\"Module not found: nothing\"\u001b[39m"],
    ["application JSON log line", "{\"level\":\"error\",\"msg\":\"Module not found: Can't resolve 'x' (cached copy)\"}"],
    ["prose that mentions the phrase mid-line", "The test 'reports Module not found: for a missing dependency' passed."],
    ["a test name in build output", "✓ guards against Attempted import error: 'a' is not exported from 'b' (mentioned, not real)"],
    ["a route list that contains a path with 'module'", "├ ƒ /api/v1/module-not-found                      253 B"],
    ["indented (not at line start) Cannot find module in prose", "    handles Error: Cannot find module 'x' gracefully"],
    ["Next docs link", "https://nextjs.org/docs/messages/no-cache"],
  ];
  it.each(BENIGN)("%s", async (_name, block) => {
    expect(await verdict(inject(block))).toBe(true);
  });
});

describe("true positives in every shape webpack and Node print them", () => {
  const BAD: [string, string, string][] = [
    ["warning with directory suffix", "./src/lib/a.ts\nModule not found: Can't resolve 'left-pad' in '/home/runner/work/x/src/lib'", "module-not-found"],
    ["error without directory suffix", "./src/lib/a.ts\nModule not found: Can't resolve 'left-pad'", "module-not-found"],
    ["legacy 'Error:' wording", "Module not found: Error: Can't resolve 'left-pad' in '/d'", "module-not-found"],
    ["package subpath not exported", "Module not found: Package path ./internal is not exported from package /app/node_modules/pkg (see exports field in package.json)", "module-not-found"],
    ["leading status glyph", " ⚠ Module not found: Can't resolve 'left-pad'", "module-not-found"],
    ["Next missing named export", "Attempted import error: 'present' is not exported from '@/lib/x' (imported as 'present').", "missing-export"],
    ["webpack classic missing export", "export 'present' (imported as 'present') was not found in './x' (possible exports: other)", "missing-export"],
    ["Node cannot-find-module during page-data collection", "[Error: Cannot find module '.prisma/client/default'", "cannot-find-module"],
    ["Node cannot-find-module (plain)", "Error: Cannot find module 'left-pad'", "cannot-find-module"],
    ["ANSI-coloured diagnostic", "\u001b[1mModule not found\u001b[22m: Can't resolve 'left-pad'", "module-not-found"],
  ];
  it.each(BAD)("%s", async (_name, block, kind) => {
    const a = await analyze(inject(block));
    expect(a.findings.map((f) => f.kind)).toContain(kind);
    expect(await verdict(inject(block))).toBe(false);
  });
  it("a diagnostic is found wherever it is: first line, middle, last line, with CRLF line endings", async () => {
    const d = "Module not found: Can't resolve 'left-pad'";
    const clean = fixture("clean-real-ci.txt");
    for (const t of [`${d}\n${clean}`, clean.replace("Generating static pages", `${d}\nGenerating static pages`), `${clean}\n${d}`, inject(d).replace(/\n/g, "\r\n")]) {
      expect((await analyze(t)).findings.length).toBeGreaterThanOrEqual(1);
    }
  });
  it("repeats across compilers are reported once, with every log line listed", async () => {
    const { summarizeFindings } = await mod;
    const s = summarizeFindings((await analyze(fixture("unresolved-dynamic-and-missing-export-real.txt"))).findings);
    expect(s).toHaveLength(2);
    expect(s.find((x: { kind: string }) => x.kind === "missing-export")).toMatchObject({ count: 2, lines: [16, 22] });
  });
});

describe("fails closed: a log that proves nothing is not a pass", () => {
  it.each([["empty", ""], ["whitespace only", "\n  \n"], ["gate header only", "### gate: build (required)\n$ npm run build\n"], ["build output with no compile marker", "> next build\n   Creating an optimized production build ...\n"]])("%s", async (_n, text) => {
    const a = await analyze(text);
    expect(a.sawCompileMarker).toBe(false);
    expect(a.problems.length).toBe(1);
    expect(await verdict(text)).toBe(false);
  });
  it("either Next marker satisfies the completeness requirement", async () => {
    expect(await verdict(" ✓ Compiled successfully in 19.4s\n")).toBe(true);
    expect(await verdict(" ⚠ Compiled with warnings in 12.9s\n")).toBe(true);
  });
});

describe("as run in CI: the command line and the gate harness", () => {
  const run = (...args: string[]) => spawnSync(process.execPath, [GUARD, ...args], { encoding: "utf8" });
  it("exit codes: 0 clean, 1 findings, 1 incomplete, 2 unreadable log; findings go to stderr with file and log line", () => {
    expect(run(path.join(FX, "clean-real-ci.txt")).status).toBe(0);
    const bad = run(path.join(FX, "nodemailer-warning-real-ci.txt"));
    expect(bad.status).toBe(1);
    expect(bad.stderr).toMatch(/FAIL: module-not-found in \.\/src\/lib\/email\.ts: Module not found: Can't resolve 'nodemailer'.*log line 25/);
    const empty = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "bl-")), "empty.log"); fs.writeFileSync(empty, "");
    expect(run(empty).status).toBe(1);
    expect(run(path.join(os.tmpdir(), "does-not-exist-build.log")).status).toBe(2);
    expect(run().status).toBe(2);
  });
  it("through scripts/ci/gate.sh (the workflow's exact invocation): a broken build log FAILS the required gate and the failure is recorded; a clean one passes", () => {
    const gate = (log: string) => {
      const ev = fs.mkdtempSync(path.join(os.tmpdir(), "gate-"));
      fs.mkdirSync(path.join(ev, "logs"));
      fs.copyFileSync(log, path.join(ev, "logs", "build.log")); // gate.sh itself writes logs/<id>.log; here we stage what the build gate would have left
      const r = spawnSync("bash", [path.join(root, "scripts/ci/gate.sh"), "build-resolution", "required", "--", `node ${GUARD} "$CI_EVIDENCE_DIR/logs/build.log"`], {
        encoding: "utf8", env: { ...process.env, CI_EVIDENCE_DIR: ev, CI_REDACT_VARS: "SESSION_SECRET" },
      });
      return { status: r.status, tsv: fs.readFileSync(path.join(ev, "gates.tsv"), "utf8"), out: r.stdout + r.stderr };
    };
    const broken = gate(path.join(FX, "nodemailer-warning-real-ci.txt"));
    expect(broken.status).toBe(1);
    expect(broken.tsv.split("\t").slice(0, 3)).toEqual(["build-resolution", "required", "1"]);
    expect(broken.out).toContain("Required gate failed");
    const clean = gate(path.join(FX, "clean-real-ci.txt"));
    expect(clean.status).toBe(0);
    expect(clean.tsv.split("\t").slice(0, 3)).toEqual(["build-resolution", "required", "0"]);
  });
});
